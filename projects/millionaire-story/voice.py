"""Voiceover for "How I Got This Car".

Synthesizes every script line with Kokoro-82M, joins them with pauses, then
uses Whisper to get word timings (for synced captions) and computes a
per-frame mouth envelope (for lip sync). Writes voice.wav and voice.js.

Usage:
  python voice.py --kokoro kokoro-q8.onnx --voices voices.npz --whisper whisper-small/ --out .
"""
import argparse
import json
import os
import subprocess

import numpy as np
import soundfile as sf

# (scene, speaker, text, pause after in seconds)
# speaker "on" = the stickman says it on screen (lip sync), "vo" = narration.
SCRIPT = [
    ('car', 'on', 'Let me tell you how I got this luxury car.', 0.55),
    ('car', 'on', 'One year ago, I was completely broke.', 0.9),
    ('lose', 'vo', 'I was trading every single day...', 0.15),
    ('lose', 'vo', 'and losing every single day.', 0.45),
    ('lose', 'vo', 'I bought the tops. I sold the bottoms.', 0.35),
    ('lose', 'vo', 'Until one day, I blew my entire account.', 0.9),
    ('break', 'vo', 'So I stepped away. No charts. No trades.', 0.35),
    ('break', 'vo', 'Just me, my couch, and my phone.', 0.5),
    ('find', 'vo', "And that's when I found TJR.", 0.35),
    ('find', 'vo', 'A day trader who actually teaches people how to trade.', 0.6),
    ('study', 'vo', 'So I studied everything. His guides. His videos. His rules.', 0.35),
    ('study', 'vo', 'Risk management. Patience. No FOMO.', 0.35),
    ('study', 'vo', 'Day after day, for thirty days straight.', 0.7),
    ('win', 'vo', 'Then, I waited for my setup...', 0.35),
    ('win', 'vo', 'pressed buy...', 0.55),
    ('win', 'vo', 'and caught my first big win!', 0.9),
    ('meet', 'vo', 'Months later, I finally met TJR in person.', 0.4),
    ('meet', 'on', 'Thank you, man. Your videos changed my life.', 0.8),
    ('million', 'vo', 'That one win became a system.', 0.3),
    ('million', 'vo', 'And that system made my first million.', 0.8),
    ('car', 'on', "And that's how I got this car.", 0.55),
    ('car', 'on', "So if you're losing right now, don't quit.", 0.35),
    ('car', 'on', 'Learn. Stay disciplined. Your win is coming.', 1.2),
]
VOICE = 'am_michael'
SPEED = 1.05
LEAD_IN = 0.6
FPS = 30


def load16k(path):
    raw = subprocess.run(['ffmpeg', '-v', 'error', '-i', path, '-ac', '1', '-ar', '16000', '-f', 'f32le', '-'],
                         capture_output=True, check=True).stdout
    return np.frombuffer(raw, np.float32)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--kokoro', required=True)
    ap.add_argument('--voices', required=True)
    ap.add_argument('--whisper', required=True)
    ap.add_argument('--out', default='.')
    a = ap.parse_args()

    from kokoro_onnx import Kokoro
    from faster_whisper import WhisperModel

    tts = Kokoro(a.kokoro, a.voices)
    asr = WhisperModel(a.whisper, device='cpu', compute_type='int8')

    sr = 24000
    parts = [np.zeros(int(LEAD_IN * sr), np.float32)]
    t = LEAD_IN
    lines = []
    tmp = os.path.join(a.out, '_line.wav')
    for scene, speaker, text, pause in SCRIPT:
        audio, sr = tts.create(text, voice=VOICE, speed=SPEED)
        audio = audio.astype(np.float32)
        sf.write(tmp, audio, sr)
        segs, _ = asr.transcribe(load16k(tmp), language='en', word_timestamps=True)
        words, heard = [], []
        for s in segs:
            heard.append(s.text.strip())
            words += [{'w': w.word.strip(), 's': round(t + w.start, 3), 'e': round(t + w.end, 3)} for w in s.words]
        dur = len(audio) / sr
        lines.append({'scene': scene, 'speaker': speaker, 'text': text, 'heard': ' '.join(heard),
                      's': round(t, 3), 'e': round(t + dur, 3), 'words': words})
        print(f'{t:6.2f}s  {text}\n        heard: {" ".join(heard)}')
        parts += [audio, np.zeros(int(pause * sr), np.float32)]
        t += dur + pause
    os.remove(tmp)
    voice = np.concatenate(parts)
    sf.write(os.path.join(a.out, 'voice.wav'), voice, sr)

    # mouth envelope: RMS per video frame, normalized and smoothed
    hop = sr // FPS
    n = len(voice) // hop + 1
    rms = np.array([np.sqrt(np.mean(voice[i * hop:(i + 1) * hop] ** 2) + 1e-12) for i in range(n)])
    rms = np.clip(rms / (np.percentile(rms[rms > 1e-3], 90) + 1e-9), 0, 1.2)
    env, acc = [], 0.0
    for v in rms:
        acc = v if v > acc else acc * 0.55 + v * 0.45
        env.append(round(float(acc if acc > 0.08 else 0), 3))

    total = round(t + 0.4, 2)
    with open(os.path.join(a.out, 'voice.js'), 'w') as f:
        f.write('// Generated by voice.py: line + word timings and mouth envelope.\n')
        f.write('window.VOICE = ' + json.dumps({'duration': total, 'fps': FPS, 'lines': lines, 'mouth': env}) + ';\n')
    print('total', total)


if __name__ == '__main__':
    main()
