"""TJR's voice lines for "Rags to Riches 3" (a generic Kokoro voice, not his real one).

Synthesizes each line in timeline.js `voice`, checks it with Whisper, places it at its time,
and writes voice.flac (44.1 kHz mono) plus voice.js (per-line mouth envelopes for lip sync).
A line with "ffwd" is sped up (pitch and tempo) for the fast-forward montage.

Usage:
  python voice.py --kokoro kokoro-q8.onnx --voices voices.npz --whisper whisper-small/ --out .
"""
import argparse
import json
import os
import re
import subprocess
import sys

import numpy as np
import soundfile as sf

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', '..', 'tools'))
from voicekit import envelope, to16k  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
TL = json.loads(re.search(r'window\.TL = (\{.*\});', open(os.path.join(HERE, 'timeline.js')).read(), re.S).group(1))
VOICE, SPEED, SR, OUT_SR = 'am_fenrir', 0.95, 24000, 44100


def resample(a, src, dst):
    raw = subprocess.run(['ffmpeg', '-v', 'error', '-f', 'f32le', '-ar', str(src), '-ac', '1', '-i', '-',
                          '-ar', str(dst), '-f', 'f32le', '-'], input=a.astype(np.float32).tobytes(),
                         capture_output=True, check=True).stdout
    return np.frombuffer(raw, np.float32)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--kokoro', required=True)
    ap.add_argument('--voices', required=True)
    ap.add_argument('--whisper', required=True)
    ap.add_argument('--out', default='.')
    a = ap.parse_args()

    from faster_whisper import WhisperModel
    from kokoro_onnx import Kokoro

    tts = Kokoro(a.kokoro, a.voices)
    asr = WhisperModel(a.whisper, device='cpu', compute_type='int8')
    mix = np.zeros(int(TL['duration'] * OUT_SR), np.float32)
    lines = []
    for ln in TL['voice']:
        audio, _ = tts.create(ln['text'], voice=VOICE, speed=SPEED)
        audio = audio.astype(np.float32)
        heard = ' '.join(s.text.strip() for s in asr.transcribe(to16k(audio), language='en')[0])
        if ln.get('ffwd'):
            # play it back faster: chipmunk pitch + tempo, like a tape on fast-forward
            audio = resample(audio, int(SR * ln['ffwd']), SR)
        dur = len(audio) / SR
        lines.append({'s': ln['t'], 'e': round(ln['t'] + dur, 3), 'text': ln['text'], 'heard': heard,
                      'mouth': envelope(audio)})
        print(f"{ln['t']:6.2f}-{ln['t'] + dur:6.2f}s {ln['text']}\n               heard: {heard}")
        hi = resample(audio, SR, OUT_SR)
        i = int(ln['t'] * OUT_SR)
        mix[i:i + len(hi)] += hi[: len(mix) - i]
    mix /= max(1.0, np.max(np.abs(mix)) / 0.95)
    sf.write(os.path.join(a.out, 'voice.flac'), mix, OUT_SR)
    with open(os.path.join(a.out, 'voice.js'), 'w') as f:
        f.write("// Generated by voice.py: TJR's line timings and per-line mouth envelopes.\n")
        f.write('window.VOICE = ' + json.dumps({'fps': 30, 'lines': lines}) + ';\n')


if __name__ == '__main__':
    main()
