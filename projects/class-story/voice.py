"""Voices for "They Laughed In Class".

Several speakers: the narrator/hero (am_michael), classmates (other Kokoro voices)
and a synthesized crowd laugh. Each line is checked with Whisper; word timings and
a per-line mouth envelope (for lip sync) go to voice.js, the mixed track to voice.wav.

Usage:
  python voice.py --kokoro kokoro-q8.onnx --voices voices.npz --whisper whisper-small/ --out .
"""
import argparse
import json
import os
import sys

import numpy as np
import soundfile as sf

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'tools'))

SPEAKERS = {
    'nar': ('am_michael', 1.12),   # the hero narrating
    'hero': ('am_michael', 1.12),  # the hero talking on screen
    'k1': ('am_echo', 1.1),
    'k2': ('af_nicole', 1.05),
    'k3': ('am_liam', 1.1),
    'k4': ('af_sarah', 1.05),
}
# (scene, speaker, text, gap after; negative overlaps the next line)
SCRIPT = [
    ('class', 'nar', 'Everyone in my class laughed at me.', 0.15),
    ('class', 'k1', 'Bro lost money again!', 0.0),
    ('class', 'laugh', 'Ha ha ha ha!', 0.15),
    ('lose', 'nar', 'Because I was trading in the back of class, and losing.', 0.1),
    ('lose', 'nar', 'Every. Single. Time.', 0.3),
    ('lose', 'nar', 'Minus fifty. Minus a hundred. Minus everything.', 0.5),
    ('quit', 'nar', 'I almost quit.', 0.7),
    ('night', 'nar', 'Then, at 2 AM, I found a TJR motivational video.', 0.25),
    ('night', 'nar', 'And it hit different.', 0.75),
    ('grind', 'nar', 'So I kept going.', 0.2),
    ('grind', 'nar', 'I studied his guides. Practiced every day. Kept my losses small.', 0.25),
    ('grind', 'nar', 'Week one, red. Week two, closer. Week four...', 0.35),
    ('grind', 'nar', 'Green!', 0.35),
    ('grind', 'nar', 'Then green again. And again. And again.', 0.5),
    ('class2', 'nar', 'Now, the same class that laughed at me...', 0.15),
    ('class2', 'k2', 'Yo, how do I start trading?', -0.1),
    ('class2', 'k3', 'Teach me, bro!', -0.1),
    ('class2', 'k4', 'Please help me!', 0.45),
    ('end', 'hero', 'Funny how that works.', 0.4),
    ('end', 'hero', 'Keep going. Your turn is coming.', 1.2),
]
SR = 24000
LEAD_IN = 0.5
FPS = 30


def to16k(a, sr):
    return np.interp(np.arange(0, len(a), sr / 16000), np.arange(len(a)), a).astype(np.float32)


def envelope(a, sr):
    hop = sr // FPS
    n = len(a) // hop + 1
    rms = np.array([np.sqrt(np.mean(a[i * hop:(i + 1) * hop] ** 2) + 1e-12) for i in range(n)])
    rms = np.clip(rms / (np.percentile(rms[rms > 1e-3], 90) + 1e-9), 0, 1.2) if np.any(rms > 1e-3) else rms * 0
    env, acc = [], 0.0
    for v in rms:
        acc = v if v > acc else acc * 0.55 + v * 0.45
        env.append(round(float(acc if acc > 0.08 else 0), 3))
    return env


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--kokoro', required=True)
    ap.add_argument('--voices', required=True)
    ap.add_argument('--whisper', required=True)
    ap.add_argument('--out', default='.')
    a = ap.parse_args()

    from kokoro_onnx import Kokoro
    from faster_whisper import WhisperModel
    from synth import SR as SYN_SR, crowd_laugh

    tts = Kokoro(a.kokoro, a.voices)
    asr = WhisperModel(a.whisper, device='cpu', compute_type='int8')

    t = LEAD_IN
    clips, lines = [], []
    for scene, spk, text, gap in SCRIPT:
        if spk == 'laugh':
            raw = crowd_laugh()
            audio = np.interp(np.arange(0, len(raw), SYN_SR / SR), np.arange(len(raw)), raw).astype(np.float32)
            words, heard = [], '(crowd laugh)'
        else:
            voice, speed = SPEAKERS[spk]
            audio, _ = tts.create(text, voice=voice, speed=speed)
            audio = audio.astype(np.float32)
            segs, _ = asr.transcribe(to16k(audio, SR), language='en', word_timestamps=True)
            segs = list(segs)
            heard = ' '.join(s.text.strip() for s in segs)
            words = [{'w': w.word.strip(), 's': round(t + w.start, 3), 'e': round(t + w.end, 3)} for s in segs for w in s.words]
        dur = len(audio) / SR
        lines.append({'scene': scene, 'speaker': spk, 'text': text, 'heard': heard, 's': round(t, 3),
                      'e': round(t + dur, 3), 'words': words, 'mouth': envelope(audio, SR)})
        print(f'{t:6.2f}s {spk:5s} {text}\n               heard: {heard}')
        clips.append((t, audio))
        t += dur + gap

    total = t + 0.3
    mix = np.zeros(int(total * SR) + SR, np.float32)
    for t0, audio in clips:
        i = int(t0 * SR)
        mix[i:i + len(audio)] += audio
    mix = mix[: int(total * SR)]
    mix /= max(1.0, np.max(np.abs(mix)) / 0.95)
    sf.write(os.path.join(a.out, 'voice.wav'), mix, SR)
    with open(os.path.join(a.out, 'voice.js'), 'w') as f:
        f.write('// Generated by voice.py: line + word timings and per-line mouth envelopes.\n')
        f.write('window.VOICE = ' + json.dumps({'duration': round(total, 2), 'fps': FPS, 'lines': lines}) + ';\n')
    print('total', round(total, 2))


if __name__ == '__main__':
    main()
